"""Generate reviewable Standard Avalon wrapper/component metadata. No board IO."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MEM = {
    'fb_write': 'memFbWrite', 'fb_color_write': 'memFbColorWrite',
    'fb_aux_write': 'memFbAuxWrite', 'fb_color_read': 'memFbColorRead',
    'fb_aux_read': 'memFbAuxRead', 'tex': 'memTex',
}
SLAVE = [('address', 12, 'input'), ('read', 1, 'input'), ('write', 1, 'input'),
         ('writedata', 32, 'input'), ('byteenable', 4, 'input'),
         ('readdata', 32, 'output'), ('readdatavalid', 1, 'output'), ('waitrequest', 1, 'output')]
MASTER = [('address', 32, 'output'), ('read', 1, 'output'), ('write', 1, 'output'),
          ('writedata', 32, 'output'), ('byteenable', 4, 'output'), ('burstcount', 11, 'output'),
          ('readdata', 32, 'input'), ('readdatavalid', 1, 'input'), ('waitrequest', 1, 'input')]
SUFFIX = {'address': 'address', 'read': 'read', 'write': 'write', 'writedata': 'writeData',
          'byteenable': 'byteEnable', 'burstcount': 'burstCount', 'readdata': 'readData',
          'readdatavalid': 'readDataValid', 'waitrequest': 'waitRequestn'}

def declaration(name, width, direction):
    return f'{direction} wire ' + (f'[{width-1}:0] ' if width > 1 else '') + name

ports = ['input wire clk', 'input wire reset_n']
for prefix, desc in [('ctl', SLAVE), ('sst', SLAVE)]:
    for name, width, direction in desc:
        ports.append(declaration(prefix+'_'+name, 22 if prefix == 'sst' and name == 'address' else width, direction))
for prefix in MEM:
    ports += [declaration(prefix+'_'+name, width, direction) for name, width, direction in MASTER]
v = ['// Generated by prepare-project.py; CPU SST address is a WORD index.',
     'module gpu_spinal_standard(\n    '+',\n    '.join(ports)+'\n);',
     'wire flush, pipeline_busy, writeback_busy, render_work_busy, fence_busy;',
     'wire barrier_request, barrier_done, barrier_error;']
for name, width, _ in MASTER:
    v.append('wire '+(f'[{width-1}:0] ' if width > 1 else '')+'raw_fb_write_'+name+';')
connections = ['.clk(clk)', '.reset(~reset_n)', '.io_hdmi_clock(clk)', '.io_hdmi_reset(~reset_n)',
               '.io_fenceFlush(flush)', '.io_publicationPipelineBusy(pipeline_busy)',
               '.io_publicationWriteBusy(writeback_busy)',
               '.io_publicationRenderWorkBusy(render_work_busy)',
               '.io_publicationExternalBusBusy(fence_busy)']
for name, _, _ in SLAVE:
    connections.append(f'.io_h2fLw_{name}(sst_{name})')
for prefix, core in MEM.items():
    for name, _, _ in MASTER:
        signal = ('raw_fb_write_' if prefix == 'fb_write' else prefix+'_')+name
        if name == 'waitrequest':
            signal = '~'+signal
        connections.append(f'.io_{core}_{SUFFIX[name]}({signal})')
v.append('SpinalStandardCore renderer(\n    '+',\n    '.join(connections)+'\n);')
connections = ['.clk(clk)', '.reset_n(reset_n)', '.flush(flush)', '.pipeline_busy(pipeline_busy)',
               '.writeback_busy(writeback_busy | fence_busy)', '.barrier_request(barrier_request)',
               '.barrier_done(barrier_done)', '.barrier_error(barrier_error)']
connections += [f'.{name}(ctl_{name})' for name, _, _ in SLAVE]
connections.append('.memory_active('+ ' | '.join(f'{prefix}_read | {prefix}_write' for prefix in MEM)+')')
v.append('gpu2_sidecar publication(\n    '+',\n    '.join(connections)+'\n);')
connections = ['.clk(clk)', '.reset_n(reset_n)', '.request(barrier_request)',
               '.quiescent(!render_work_busy && !writeback_busy)', '.busy(fence_busy)',
               '.done(barrier_done)', '.error(barrier_error)']
for name, _, _ in MASTER:
    connections += [f'.s_{name}(raw_fb_write_{name})', f'.m_{name}(fb_write_{name})']
v.append('avalon_frame_fence fence(\n    '+',\n    '.join(connections)+'\n);\nendmodule\n')
(ROOT/'gpu_spinal_standard.v').write_text('\n'.join(v), encoding='utf-8')

t = ['package require -exact qsys 13.1',
     'set_module_property NAME gpu_spinal_standard', 'set_module_property VERSION 2.0',
     'set_module_property GROUP "GPU Platform"', 'set_module_property INSTANTIATE_IN_SYSTEM_MODULE true',
     'add_fileset QUARTUS_SYNTH QUARTUS_SYNTH',
     'set_fileset_property QUARTUS_SYNTH TOP_LEVEL gpu_spinal_standard']
for file in ['gpu_spinal_standard.v', 'gpu2_sidecar.v', 'avalon_frame_fence.v']:
    t.append(f'add_fileset_file {file} VERILOG PATH {file}'+(' TOP_LEVEL_FILE' if file=='gpu_spinal_standard.v' else ''))
for path in sorted((ROOT/'rtl').glob('*')):
    if path.suffix in ('.v', '.sv', '.bin'):
        typ = {'.v':'VERILOG', '.sv':'SYSTEM_VERILOG', '.bin':'OTHER'}[path.suffix]
        t.append(f'add_fileset_file rtl/{path.name} {typ} PATH rtl/{path.name}')
t += ['add_interface clock clock end', 'add_interface_port clock clk clk Input 1',
      'add_interface reset reset end', 'set_interface_property reset associatedClock clock',
      'set_interface_property reset synchronousEdges DEASSERT', 'add_interface_port reset reset_n reset_n Input 1']
for interface, prefix, desc, units, span in [('control', 'ctl', SLAVE, 'SYMBOLS', 4096), ('sst', 'sst', SLAVE, 'WORDS', 16777216)]:
    t += [f'add_interface {interface} avalon end', f'set_interface_property {interface} associatedClock clock',
          f'set_interface_property {interface} associatedReset reset', f'set_interface_property {interface} addressUnits {units}',
          f'set_interface_property {interface} maximumPendingReadTransactions 1',
          f'set_interface_property {interface} explicitAddressSpan {span}', f'set_interface_property {interface} readLatency 0']
    for name, width, direction in desc:
        width = 22 if interface == 'sst' and name == 'address' else width
        t.append(f'add_interface_port {interface} {prefix}_{name} {name} {direction.title()} {width}')
for prefix in MEM:
    t += [f'add_interface {prefix} avalon start', f'set_interface_property {prefix} associatedClock clock',
          f'set_interface_property {prefix} associatedReset reset', f'set_interface_property {prefix} addressUnits SYMBOLS',
          f'set_interface_property {prefix} burstcountUnits WORDS', f'set_interface_property {prefix} bitsPerSymbol 8',
          f'set_interface_property {prefix} linewrapBursts false']
    for name, width, direction in MASTER:
        t.append(f'add_interface_port {prefix} {prefix}_{name} {name} {direction.title()} {width}')
(ROOT/'gpu_spinal_standard_hw.tcl').write_text('\n'.join(t)+'\n', encoding='utf-8')
print('Generated Standard wrapper and component metadata')
